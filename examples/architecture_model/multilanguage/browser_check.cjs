"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const {pathToFileURL} = require("node:url");

async function main() {
  const [modulePath, executablePath, html, modelPath, output] = process.argv.slice(2);
  const {chromium} = require(path.resolve(modulePath));
  const hash = () => crypto.createHash("sha256").update(fs.readFileSync(modelPath)).digest("hex");
  const before = hash();
  const browser = await chromium.launch({executablePath, headless: true});
  const page = await browser.newPage({viewport: {width: 1600, height: 1000}});
  const errors = [];
  page.on("pageerror", error => errors.push(String(error)));
  await page.goto(pathToFileURL(path.resolve(html)).href);
  assert.match(await page.locator("#identity").innerText(), /revision/i);
  const model = JSON.parse(fs.readFileSync(modelPath, "utf8"));
  await page.selectOption("#scenario", "open-document");
  assert.match(await page.locator("#current").innerText(), /open-action/);
  await page.click("#next");
  assert.match(await page.locator("#current").innerText(), /open-ipc/);
  await page.click("#next");
  assert.match(await page.locator("#current").innerText(), /open-command/);
  await page.click("#collapse-all");
  assert.match(await page.locator("#current").innerText(), /open-command/);
  assert.match(await page.locator("#nodes").innerText(), /Current step inside/);
  await page.click("#expand-all");
  await page.click("#back");
  assert.match(await page.locator("#current").innerText(), /open-ipc/);
  await page.selectOption("#scenario", "preview-document");
  assert.match(await page.locator("#current").innerText(), /preview-action/);
  await page.click("#next");
  await page.click("#next");
  await page.click("#next");
  assert.match(await page.locator("#current").innerText(), /preview-service/);
  await page.selectOption("#scenario", "open-document");
  assert.match(await page.locator("#current").innerText(), /open-ipc/);
  await page.locator("#relations button").filter({hasText: "Candidate Tauri"}).click();
  await page.locator("#detail summary").filter({hasText: "Cross-boundary contract"}).click();
  assert.match(await page.locator("#detail").innerText(), /candidate/);
  await page.locator('details[data-binding-id="invoke"] > summary').click();
  assert.match(await page.locator("#detail").innerText(), /typescript/);
  assert.match(await page.locator("#detail").innerText(), /frontend/);
  assert.match(await page.locator("#detail").innerText(), /Workspace bytes differ/);
  await page.locator('details[data-binding-id="command"] > summary').click();
  assert.match(await page.locator("#detail").innerText(), /rust/);
  assert.match(await page.locator("#detail").innerText(), /backend/);
  await page.screenshot({path: output + ".png", fullPage: true});
  assert.deepEqual(errors, []);
  await browser.close();
  assert.equal(hash(), before);
  fs.writeFileSync(output + ".json", JSON.stringify({browser: "local Chrome headless / Playwright", model_id: model.id, revision: model.revision, model_sha256_before: before, model_sha256_after: hash(), checks: ["cross-language playback", "collapse/expand preserve position", "back history", "scenario switching shares components and preserves position", "candidate contract", "both roots and languages in evidence", "historical mismatch withheld", "no JavaScript errors", "model bytes unchanged"]}, null, 2) + "\n");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
