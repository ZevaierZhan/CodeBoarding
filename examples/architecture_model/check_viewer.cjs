/* Usage: PLAYWRIGHT_MODULE=/path/to/playwright node .../check_viewer.cjs OUTPUT_DIR */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const crypto = require('node:crypto');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const directory=path.resolve(process.argv[2]);
  const evidence=path.join(directory,'browser');fs.mkdirSync(evidence,{recursive:true});
  const modelPath=path.join(directory,'architecture-model.json');
  const digest=()=>crypto.createHash('sha256').update(fs.readFileSync(modelPath)).digest('hex');
  const before=digest();
  const browser=await chromium.launch({channel:process.env.CHROME_CHANNEL || 'chrome',headless:true});
  const context=await browser.newContext({offline:true,viewport:{width:1500,height:1050},reducedMotion:'reduce'});
  const page=await context.newPage();
  const errors=[],requests=[],checks=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>requests.push(request.url()));
  const open=async file=>{await page.goto(pathToFileURL(path.join(directory,file)).href);await page.locator('.node').first().waitFor();};
  const current=()=>page.locator('#current').textContent();
  const click=async id=>page.locator('#'+id).click();
  const snapshot=async name=>page.screenshot({path:path.join(evidence,name+'.png'),fullPage:true});
  const choice=async kind=>page.locator('#choices button').filter({hasText:kind}).click();
  try {
    await open('01-purchase.html');
    assert.equal(await page.locator('#scenario option').count(),1);
    assert.match(await current(),/business-A-validate/);
    assert.equal(await page.locator('#steps .step').first().getAttribute('aria-current'),'false');
    assert.ok(await page.locator('#graph path').count()>2);
    await page.locator('#relations button').first().click();
    assert.match(await page.locator('#detail').textContent(),/Purchase and quotation call shared pricing/);
    await click('inspect-business');
    assert.match(await page.locator('#detail').textContent(),/business-A/);
    checks.push('A: real SVG graph, entry differs from first display step');
    await open('02-shared-businesses.html');
    assert.equal(await page.locator('.node').count(),4);
    await choice('quantity > 0');
    assert.match(await current(),/business-A-price/);
    await click('collapse-all');
    assert.equal(await page.locator('.node').count(),1);
    assert.match(await page.locator('.node.current').textContent(),/Current step inside.*business-A-price/);
    await page.locator('#focus').check();
    assert.match(await current(),/business-A-price/);
    await snapshot('collapsed-current-step');
    await click('expand-all');
    assert.equal(await page.locator('[data-component-id="policy"].current').count(),1);
    assert.equal(await page.locator('#graph').evaluate(svg=>[...svg.querySelectorAll('text')].every(label=>{
      const box=label.getBBox();return box.x+box.width <= svg.width.baseVal.value;
    })),true);
    await page.locator('#tree button.object').filter({hasText:'policy'}).click();
    await page.locator('#detail details').filter({has:page.locator('summary').filter({hasText:'bind-total ·'})}).first().locator('summary').first().click();
    assert.match(await page.locator('#detail').textContent(),/Exact file SHA-256 matched/);
    assert.match(await page.locator('#detail').textContent(),/return quantity \* 10/);
    await snapshot('source-evidence');
    await page.locator('#scenario').selectOption('business-B');
    await click('next');
    assert.match(await current(),/business-B-price/);
    assert.equal(await page.locator('[data-component-id="policy"].current').count(),1);
    await page.locator('#scenario').selectOption('business-A');
    assert.match(await current(),/business-A-price/);
    checks.push('Hierarchy collapse/expand and focus preserve step; A/B share policy ID; switching restores A step; hash-verified source visible');
    await click('back');assert.match(await current(),/business-A-validate/);
    await click('play');
    await page.waitForFunction(()=>document.getElementById('play').textContent==='Play');
    assert.match(await current(),/business-A-validate/);
    assert.match(await page.locator('#playback-status').textContent(),/Paused/);
    await choice('quantity <= 0');assert.match(await current(),/business-A-reject/);
    await click('play');
    await page.waitForFunction(()=>document.getElementById('play').textContent==='Play');
    assert.match(await current(),/business-A-reject/);
    await snapshot('branch-loop-paused');
    await choice('loop →');assert.match(await current(),/business-A-validate/);
    await click('back');assert.match(await current(),/business-A-reject/);
    await choice('return →');assert.match(await current(),/business-A-abandon/);
    assert.match(await page.locator('#playback-status').textContent(),/unexplained gap/);
    await click('back');assert.match(await current(),/business-A-reject/);
    await click('reset');assert.match(await current(),/business-A-validate/);
    await choice('quantity > 0');await click('play');
    await page.waitForFunction(()=>document.getElementById('play').textContent==='Play');
    assert.match(await current(),/business-A-save/);
    checks.push('Explicit branches pause; loop requires selection; return exits; back follows actual path; reset and automatic next stop at missing outgoing transition');
    await open('03-source-pending.html');
    await choice('quantity > 0');
    assert.match(await page.locator('#detail').textContent(),/current pending/);
    assert.match(await page.locator('#detail').textContent(),/latest target/);
    assert.match(await page.locator('#detail').textContent(),/Workspace bytes differ/);
    await page.locator('#detail details').filter({has:page.locator('summary').filter({hasText:'bind-total ·'})}).first().locator('summary').first().click();
    assert.equal(await page.getByText('Workspace bytes differ from this evidence version; body withheld.',{exact:true}).isVisible(),true);
    await page.locator('#detail details').filter({has:page.locator('summary').filter({hasText:'Current explanation · changed'})}).first().locator('summary').first().click();
    await snapshot('source-pending');
    await open('04-reviewed.html');await choice('quantity > 0');
    assert.match(await page.locator('#detail').textContent(),/review recorded/);
    assert.match(await page.locator('#detail').textContent(),/Historical explanation · changed · historical pending/);
    assert.match(await page.locator('#detail').textContent(),/Current explanation · changed · review recorded · older target/);
    assert.match(await page.locator('#detail').textContent(),/feedback-pricing/);
    const review=page.locator('#detail details').filter({has:page.locator('summary').filter({hasText:'Current explanation · changed'})}).first();
    await review.locator('summary').first().click();
    assert.match(await review.textContent(),/business-agent/);
    assert.match(await review.textContent(),/object_versions/);
    await snapshot('reviewed-with-history');
    await click('metadata');assert.match(await page.locator('#detail').textContent(),/business-A-price/);
    checks.push('Source mismatch withholds body; historical pending survives; current confirmation explicitly names older source target; author/reason, actual fingerprints, feedback and selected business/step metadata visible');
    // A hostile fixture is created by the Python acceptance setup when supplied.
    if(fs.existsSync(path.join(directory,'untrusted.html'))){
      await open('untrusted.html');
      assert.equal(await page.evaluate(()=>window.injected),undefined);
      assert.equal(await page.locator('#detail a[href^="javascript:"]').count(),0);
      assert.match(await page.locator('.node').first().textContent(),/script/);
      checks.push('Script-closing and javascript URL payloads rendered inert as text');
    }
    await open('04-reviewed.html');await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.equal(await page.locator('#diagram-help').isVisible(),true);
    await page.locator('#canvas').focus();
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(()=>document.getElementById('canvas').scrollLeft>0);
    await snapshot('mobile');
    checks.push('390px responsive page: no document-level overflow; visible scroll instruction and focus outline; ArrowRight scrolls the diagram');
    assert.deepEqual(errors,[]);
    assert.deepEqual(requests.filter(url=>!url.startsWith('file:')),[]);
    assert.equal(digest(),before);
    checks.push('Offline file loading: no external requests, no page errors; model hash/revision unchanged');
    fs.writeFileSync(path.join(evidence,'results.json'),JSON.stringify({browser:await browser.version(),checks,errors,requests,model_sha256_before:before,model_sha256_after:digest()},null,2));
    console.log(JSON.stringify({checks,errors,model_sha256:before},null,2));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
